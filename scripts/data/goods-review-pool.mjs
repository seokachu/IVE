/**
 * 상품 제목과 순번으로 리뷰 한 건을 만든다.
 * seed가 같으면 결과도 같아 재실행해도 흔들리지 않는다.
 */
export const buildReview = (title, seed) => {
  const bodies = BODIES[categoryOf(title)] ?? BODIES.etc;
  const [rating, body] = bodies[seed % bodies.length];

  const tails = rating >= 4 ? TAILS_POSITIVE : TAILS_NEGATIVE;
  //본문과 꼬리를 서로 다른 주기로 돌려 조합이 반복되지 않게 한다
  const tail = tails[Math.floor(seed / bodies.length) % tails.length];

  return { rating, content: `${body}${tail}` };
};
